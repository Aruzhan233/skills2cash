export const Textarea = forwardRef<HTMLTextAreaElement, TextareaHTMLAttributes<HTMLTextAreaElement>>(function Textarea(
  { className, rows = 3, ...rest },
  ref,
) {
  return <textarea ref={ref} rows={rows} className={cn(fieldBase, "resize-y leading-relaxed", className)} {...rest} />;
});

export function Select({ className, ...rest }: React.SelectHTMLAttributes<HTMLSelectElement>) {
  return <select className={cn(fieldBase, "h-10", className)} {...rest} />;
}

export function PageHeader({ title, sub, right, eyebrow }: { title: string; sub?: ReactNode; right?: ReactNode; eyebrow?: ReactNode }) {
  return (
    <div className="mb-8 flex animate-rise flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
      <div className="min-w-0">
        <h1 className="text-[1.75rem] font-semibold leading-tight text-ink sm:text-[2.125rem]">{title}</h1>
        {sub && <p className="mt-2 max-w-[68ch] text-sm leading-relaxed text-muted">{sub}</p>}
        {/* `eyebrow` is page meta (week, disclaimers); it follows the title rather than sitting above it */}
        {eyebrow && <div className="mt-3">{eyebrow}</div>}
      </div>
      {right && <div className="flex shrink-0 flex-wrap gap-2">{right}</div>}
    </div>
  );
}

export function scoreTone(score: number | null): Tone {
  if (score === null) return "neutral";
  if (score >= 80) return "good";
  if (score >= 60) return "neutral";
  return "warn";
}

export function ScorePill({ score, suffix = "/100" }: { score: number | null; suffix?: string }) {
  return (
    <Badge tone={scoreTone(score)}>
      {score === null ? "Not enough data" : `${score}${suffix}`}
    </Badge>
  );
}
