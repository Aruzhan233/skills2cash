"use client";
// Small shadcn-style primitives built on Tailwind (no extra runtime deps).

import Link from "next/link";
import { forwardRef, type ButtonHTMLAttributes, type InputHTMLAttributes, type ReactNode, type TextareaHTMLAttributes } from "react";
import { AlertTriangle, Bot, CheckCircle2, FlaskConical, Loader2, RotateCcw, User } from "lucide-react";
import { cn } from "@/lib/cn";

import { buttonClass, type Size, type Variant } from "./button-class";
import { LogoMark } from "./logo";

export { buttonClass };

export const Button = forwardRef<
  HTMLButtonElement,
  ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant; size?: Size; loading?: boolean }
>(function Button({ variant = "primary", size = "md", loading, className, children, disabled, ...rest }, ref) {
  return (
    <button ref={ref} className={buttonClass(variant, size, className)} disabled={disabled || loading} {...rest}>
      {loading && <Loader2 className="h-4 w-4 animate-spin" aria-hidden />}
      {children}
    </button>
  );
});

export function LinkButton({
  href,
  variant = "primary",
  size = "md",
  className,
  children,
}: {
  href: string;
  variant?: Variant;
  size?: Size;
  className?: string;
  children: ReactNode;
}) {
  return (
    <Link href={href} className={buttonClass(variant, size, className)}>
      {children}
    </Link>
  );
}

export function Card({ className, children, as: As = "section" }: { className?: string; children: ReactNode; as?: "section" | "div" | "article" }) {
  // A lit card replaces the glass material rather than stacking on it.
  const material = className?.includes("glass-lit") ? "" : "glass";
  return <As className={cn(material, "rounded-2xl p-5 sm:p-6", className)}>{children}</As>;
}

export function CardTitle({ children, sub, right }: { children: ReactNode; sub?: ReactNode; right?: ReactNode }) {
  return (
    <div className="mb-4 flex items-start justify-between gap-3">
      <div className="min-w-0">
        <h2 className="text-base font-semibold leading-snug tracking-tight text-ink">{children}</h2>
        {sub && <p className="mt-1 text-sm text-muted">{sub}</p>}
      </div>
      {right}
    </div>
  );
}

type Tone = "neutral" | "violet" | "good" | "warn" | "bad" | "spark";
const tones: Record<Tone, string> = {
  neutral: "bg-surface-3 text-ink-2 ring-1 ring-inset ring-line",
  violet: "bg-violet-tint text-violet-soft ring-1 ring-inset ring-violet/30",
  good: "bg-good/10 text-good ring-1 ring-inset ring-good/20",
  warn: "bg-warn/10 text-warn ring-1 ring-inset ring-warn/20",
  bad: "bg-bad/10 text-bad ring-1 ring-inset ring-bad/20",
  spark: "bg-spark/10 text-spark ring-1 ring-inset ring-spark/25",
};

export function Badge({ tone = "neutral", children, className, title }: { tone?: Tone; children: ReactNode; className?: string; title?: string }) {
  return (
    <span title={title} className={cn("inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-medium whitespace-nowrap", tones[tone], className)}>
      {children}
    </span>
  );
}

/** Marks a score's source: self-reported vs demonstrated through assignments/simulations. */
export function SourceBadge({ source }: { source: "self-reported" | "demonstrated" | "none" }) {
  if (source === "demonstrated")
    return (
      <Badge tone="neutral" title="Scored from completed missions or AI client simulations">
        <CheckCircle2 className="h-3 w-3" aria-hidden /> Demonstrated
      </Badge>
    );
  if (source === "self-reported")
    return (
      <Badge tone="neutral" title="Your own rating from the assessment — not yet demonstrated">
        <User className="h-3 w-3" aria-hidden /> Self-reported
      </Badge>
    );
  return <Badge tone="neutral">No data</Badge>;
}

/** Marks whether content came from the AI or from the labelled offline sample. */
export function GeneratedBadge({ by }: { by: "ai" | "sample" | null | undefined }) {
  if (by === "ai")
    return (
      <Badge tone="neutral" title="Generated by the AI — may be imperfect">
        <Bot className="h-3 w-3" aria-hidden /> AI-generated
      </Badge>
    );
  return (
    <Badge tone="warn" title="Pre-written or keyword-based offline sample — not produced by the AI">
      <FlaskConical className="h-3 w-3" aria-hidden /> Offline sample — not AI
    </Badge>
  );
}

export function Progress({ value, className, tone = "violet", label }: { value: number | null; className?: string; tone?: "violet" | "muted" | "good" | "spark"; label?: string }) {
  const v = value === null ? 0 : Math.max(0, Math.min(100, value));
  const color =
    tone === "violet"
      ? "bg-[linear-gradient(90deg,#782bff,#c5a7ff)] shadow-[0_0_12px_rgb(150_63_255/0.55)]"
      : tone === "good"
        ? "bg-good"
        : tone === "spark"
          ? "bg-[linear-gradient(90deg,#d99a3c,#f2be6a)] shadow-[0_0_10px_rgb(242_190_106/0.45)]"
          : "bg-ink-2/40";
  return (
    <div
      className={cn("h-1.5 w-full overflow-hidden rounded-full bg-white/[0.07]", className)}
      role="progressbar"
      aria-valuemin={0}
      aria-valuemax={100}
      aria-valuenow={value ?? undefined}
      aria-label={label}
    >
      <div className={cn("h-full rounded-full transition-[width] duration-700 ease-out-expo", color, value === null && "opacity-0")} style={{ width: `${v}%` }} />
    </div>
  );
}

