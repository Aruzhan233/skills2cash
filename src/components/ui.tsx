"use client";
// Small shadcn-style primitives built on Tailwind (no extra runtime deps).

import Link from "next/link";
import { forwardRef, type ButtonHTMLAttributes, type InputHTMLAttributes, type ReactNode, type TextareaHTMLAttributes } from "react";
import { AlertTriangle, Bot, CheckCircle2, FlaskConical, Loader2, RotateCcw, User } from "lucide-react";
import { cn } from "@/lib/cn";

import { buttonClass, type Size, type Variant } from "./button-class";

export { buttonClass };

export const Button = forwardRef<
  HTMLButtonElement,
  ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant; size?: Size; loading?: boolean }
>(function Button({ variant = "primary", size = "md", loading, className, children, disabled, ...rest }, ref) {
  return (
    <button ref={ref} className={buttonClass(variant, size, className)} disabled={disabled || loading} {...rest}>
      {loading && <Loader2 className="h-4 w-4 animate-spin" aria-hidden />}
      {children}
    </button>
  );
});

export function LinkButton({
  href,
  variant = "primary",
  size = "md",
  className,
  children,
}: {
  href: string;
  variant?: Variant;
  size?: Size;
  className?: string;
  children: ReactNode;
}) {
  return (
    <Link href={href} className={buttonClass(variant, size, className)}>
      {children}
    </Link>
  );
}

export function Card({ className, children, as: As = "section" }: { className?: string; children: ReactNode; as?: "section" | "div" | "article" }) {
  return <As className={cn("rounded-2xl border border-line bg-surface p-5", className)}>{children}</As>;
}

export function CardTitle({ children, sub, right }: { children: ReactNode; sub?: ReactNode; right?: ReactNode }) {
  return (
    <div className="mb-4 flex items-start justify-between gap-3">
      <div>
        <h2 className="text-base font-semibold text-ink">{children}</h2>
        {sub && <p className="mt-0.5 text-sm text-muted">{sub}</p>}
      </div>
      {right}
    </div>
  );
}

type Tone = "neutral" | "violet" | "good" | "warn" | "bad";
const tones: Record<Tone, string> = {
  neutral: "bg-surface-3 text-ink-2 border-line-strong",
  violet: "bg-violet-tint text-violet-soft border-violet/30",
  good: "bg-good/10 text-good border-good/25",
  warn: "bg-warn/10 text-warn border-warn/25",
  bad: "bg-bad/10 text-bad border-bad/25",
};

export function Badge({ tone = "neutral", children, className, title }: { tone?: Tone; children: ReactNode; className?: string; title?: string }) {
  return (
    <span
      title={title}
      className={cn("inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-xs font-medium whitespace-nowrap", tones[tone], className)}
    >
      {children}
    </span>
  );
}

/** Marks a score's source: self-reported vs demonstrated through assignments/simulations. */
export function SourceBadge({ source }: { source: "self-reported" | "demonstrated" | "none" }) {
  if (source === "demonstrated")
    return (
      <Badge tone="violet" title="Scored from completed missions or AI client simulations">
        <CheckCircle2 className="h-3 w-3" aria-hidden /> Demonstrated
      </Badge>
    );
  if (source === "self-reported")
    return (
      <Badge tone="neutral" title="Your own rating from the assessment — not yet demonstrated">
        <User className="h-3 w-3" aria-hidden /> Self-reported
      </Badge>
    );
  return <Badge tone="neutral">No data</Badge>;
}

/** Marks whether content came from the AI or from the labelled offline sample. */
export function GeneratedBadge({ by }: { by: "ai" | "sample" | null | undefined }) {
  if (by === "ai")
    return (
      <Badge tone="violet" title="Generated by the AI — may be imperfect">
        <Bot className="h-3 w-3" aria-hidden /> AI-generated
      </Badge>
    );
  return (
    <Badge tone="warn" title="Pre-written or keyword-based offline sample — not produced by the AI">
      <FlaskConical className="h-3 w-3" aria-hidden /> Offline sample — not AI
    </Badge>
  );
}

export function Progress({ value, className, tone = "violet", label }: { value: number | null; className?: string; tone?: "violet" | "muted" | "good"; label?: string }) {
  const v = value === null ? 0 : Math.max(0, Math.min(100, value));
  const color = tone === "violet" ? "bg-gradient-to-r from-violet to-violet-soft" : tone === "good" ? "bg-good" : "bg-ink-2/40";
  return (
    <div
      className={cn("h-2 w-full overflow-hidden rounded-full bg-surface-3", className)}
      role="progressbar"
      aria-valuemin={0}
      aria-valuemax={100}
      aria-valuenow={value ?? undefined}
      aria-label={label}
    >
      <div className={cn("h-full rounded-full transition-all", color, value === null && "opacity-0")} style={{ width: `${v}%` }} />
    </div>
  );
}

export function Spinner({ label = "Loading…" }: { label?: string }) {
  return (
    <div className="flex items-center gap-2 text-sm text-muted" role="status">
      <Loader2 className="h-4 w-4 animate-spin" aria-hidden /> {label}
    </div>
  );
}

export function PageLoader({ label }: { label?: string }) {
  return (
    <div className="flex min-h-[40vh] items-center justify-center">
      <Spinner label={label} />
    </div>
  );
}

export function ErrorState({
  title = "Something went wrong",
  message,
  onRetry,
  retryLabel = "Retry",
  children,
}: {
  title?: string;
  message: string;
  onRetry?: () => void;
  retryLabel?: string;
  children?: ReactNode;
}) {
  return (
    <div role="alert" className="rounded-xl border border-bad/30 bg-bad/5 p-4">
      <div className="flex items-start gap-3">
        <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0 text-bad" aria-hidden />
        <div className="min-w-0 flex-1">
          <p className="font-medium text-ink">{title}</p>
          <p className="mt-1 text-sm text-ink-2">{message}</p>
          {(onRetry || children) && (
            <div className="mt-3 flex flex-wrap gap-2">
              {onRetry && (
                <Button size="sm" variant="secondary" onClick={onRetry}>
                  <RotateCcw className="h-3.5 w-3.5" aria-hidden /> {retryLabel}
                </Button>
              )}
              {children}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

export function EmptyState({ icon, title, text, action }: { icon?: ReactNode; title: string; text: string; action?: ReactNode }) {
  return (
    <div className="flex flex-col items-center rounded-2xl border border-dashed border-line-strong bg-surface/60 px-6 py-10 text-center">
      {icon && <div className="mb-3 text-violet-soft">{icon}</div>}
      <p className="font-medium text-ink">{title}</p>
      <p className="mt-1 max-w-md text-sm text-muted">{text}</p>
      {action && <div className="mt-4">{action}</div>}
    </div>
  );
}

export function Notice({ tone = "violet", children, className }: { tone?: Tone; children: ReactNode; className?: string }) {
  return <div className={cn("rounded-xl border px-4 py-3 text-sm", tones[tone], className)}>{children}</div>;
}

const fieldBase =
  "w-full rounded-lg border border-line-strong bg-surface-2 px-3 py-2 text-sm text-ink placeholder:text-muted/70 focus:border-violet focus:outline-none focus:ring-2 focus:ring-violet/30 disabled:opacity-60";

export function Field({
  label,
  hint,
  error,
  htmlFor,
  children,
  className,
}: {
  label: string;
  hint?: ReactNode;
  error?: string | null;
  htmlFor: string;
  children: ReactNode;
  className?: string;
}) {
  return (
    <div className={className}>
      <label htmlFor={htmlFor} className="mb-1.5 block text-sm font-medium text-ink-2">
        {label}
      </label>
      {children}
      {hint && !error && <p className="mt-1 text-xs text-muted">{hint}</p>}
      {error && (
        <p className="mt-1 text-xs text-bad" role="alert">
          {error}
        </p>
      )}
    </div>
  );
}

export const Input = forwardRef<HTMLInputElement, InputHTMLAttributes<HTMLInputElement>>(function Input({ className, ...rest }, ref) {
  return <input ref={ref} className={cn(fieldBase, "h-10", className)} {...rest} />;
});

export const Textarea = forwardRef<HTMLTextAreaElement, TextareaHTMLAttributes<HTMLTextAreaElement>>(function Textarea(
  { className, rows = 3, ...rest },
  ref,
) {
  return <textarea ref={ref} rows={rows} className={cn(fieldBase, "resize-y leading-relaxed", className)} {...rest} />;
});

export function Select({ className, ...rest }: React.SelectHTMLAttributes<HTMLSelectElement>) {
  return <select className={cn(fieldBase, "h-10", className)} {...rest} />;
}

export function PageHeader({ title, sub, right, eyebrow }: { title: string; sub?: ReactNode; right?: ReactNode; eyebrow?: ReactNode }) {
  return (
    <div className="mb-6 flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
      <div>
        {eyebrow && <div className="mb-2">{eyebrow}</div>}
        <h1 className="text-2xl font-bold tracking-tight text-ink sm:text-3xl">{title}</h1>
        {sub && <p className="mt-1.5 max-w-2xl text-sm text-muted">{sub}</p>}
      </div>
      {right && <div className="flex flex-wrap gap-2">{right}</div>}
    </div>
  );
}

export function scoreTone(score: number | null): Tone {
  if (score === null) return "neutral";
  if (score >= 80) return "good";
  if (score >= 60) return "violet";
  return "warn";
}

export function ScorePill({ score, suffix = "/100" }: { score: number | null; suffix?: string }) {
  return (
    <Badge tone={scoreTone(score)}>
      {score === null ? "Not enough data" : `${score}${suffix}`}
    </Badge>
  );
}
